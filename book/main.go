// Command book renders the jwt book into one self-contained HTML file, and prints that
// file to PDF through a headless browser.
//
//	cd book && go run .                  # HTML and PDF
//	cd book && go run . -format html     # HTML only, no browser, a couple of seconds
//	cd book && go run . -format pdf      # PDF only
//
// The HTML has no external references at all: the fonts, the pagination polyfill, the
// stylesheet and the brand mark are inlined. That is the point of it. A book you can email
// as one file, or open from a USB stick in ten years, is worth more than one that depends
// on a CDN still being there.
//
// What a maintainer has to supply:
//
//   - Go 1.26 or newer.
//   - A Chromium-family browser, for the PDF only. Without one, -format html still works.
//   - assets/paged.polyfill.js, which paginates the HTML into pages with running headers
//     and a real page count. Without it the HTML renders as one long scroll and the PDF
//     has no page furniture; the generator says so and carries on.
//   - assets/inter-roman-latin.woff2 and assets/inter-italic-latin.woff2. Without them the
//     book falls back to the reader's own sans-serif and the line breaks move.
//   - ../brand/jwt-mark-on-dark.svg, generated by the brand module. Without it the cover
//     loses its mark.
//
// Every one of those is a warning rather than an error, because a book that will not build
// at all is worse than a book that builds slightly plainer.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"html/template"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// Metadata is the cover data, read from metadata.yml.
//
// There is deliberately no version field. The library's version changes with every release
// and the book does not; printing one on the cover would mean a book that is wrong the
// moment it is published, and nobody ever regenerates a PDF to bump a number.
type Metadata struct {
	Title       string   `yaml:"title"`
	Subtitle    string   `yaml:"subtitle"`
	Author      string   `yaml:"author"`
	Credit      []string `yaml:"credit"`
	Edition     string   `yaml:"edition"`
	Website     string   `yaml:"website"`
	Repository  string   `yaml:"repository"`
	License     string   `yaml:"license"`
	Description string   `yaml:"description"`
}

// Chapter is one rendered unit of the book.
type Chapter struct {
	File     string
	Number   int // 0 means the preface, which is unnumbered.
	ID       string
	Title    string
	Sections []Section
	Body     template.HTML
}

// Section is an H2 heading, used to build the book's own table of contents.
type Section struct {
	ID    string
	Title string
}

// chapterFiles is the spine, in reading order.
//
// The spine lives here rather than being discovered from the directory, so that adding a
// file does not silently add a chapter and renaming one fails loudly instead of dropping
// it. README.md is the preface and carries no number; epilogue.md is back matter.
var chapterFiles = []string{
	"README.md",
	"01-what-a-token-is.md",
	"02-signing-and-verifying.md",
	"03-claims.md",
	"04-expiry-and-time.md",
	"05-choosing-an-algorithm.md",
	"06-keys-and-rotation.md",
	"07-jwks.md",
	"08-validators.md",
	"09-revoking-tokens.md",
	"10-tokens-over-http.md",
	"11-encrypting-the-payload.md",
	"12-sharp-edges.md",
	"13-testing.md",
	"14-performance.md",
	"epilogue.md",
}

var (
	// The footer every chapter ends with, which the print build drops: a "next chapter"
	// link means nothing on paper.
	reNextFooter = regexp.MustCompile(`(?ms)^---\s*\n\s*\*\*Next( Chapter)?\*\*.*\z`)
	reH1         = regexp.MustCompile(`(?m)^# (.+)$`)
	reChapterNum = regexp.MustCompile(`^Chapter (\d+):\s*`)
)

func main() {
	format := flag.String("format", "all", "output format: html, pdf or all")
	outputDir := flag.String("output", "output", "directory to write into")
	limit := flag.Int("chapters", 0, "render only the first N spine entries, a debugging aid")
	flag.Parse()

	if err := run(*format, *outputDir, *limit); err != nil {
		fmt.Fprintln(os.Stderr, "book:", err)
		os.Exit(1)
	}
}

func run(format, outputDir string, limit int) error {
	meta, err := loadMetadata("metadata.yml")
	if err != nil {
		return err
	}

	files := chapterFiles
	if limit > 0 && limit < len(files) {
		files = files[:limit]
		fmt.Printf("book: rendering the first %d of %d spine entries\n", limit, len(chapterFiles))
	}

	chapters, err := loadChapters(files)
	if err != nil {
		return err
	}

	if err = os.MkdirAll(outputDir, 0o755); err != nil {
		return err
	}

	html, err := renderBook(meta, chapters)
	if err != nil {
		return err
	}

	htmlPath := filepath.Join(outputDir, "jwt-book.html")
	if err = os.WriteFile(htmlPath, html, 0o644); err != nil {
		return err
	}
	fmt.Printf("book: wrote %s (%d chapters, %.1f MB)\n", htmlPath, len(chapters), float64(len(html))/(1<<20))

	if format == "html" {
		return nil
	}

	browser, err := findBrowser()
	if err != nil {
		fmt.Println("book:", err)
		fmt.Println("book: the HTML is written. Install Chrome or Edge to get the PDF, or use -format html to stop asking.")
		return nil
	}

	pdfPath := filepath.Join(outputDir, "jwt-book.pdf")
	if err = printToPDF(browser, htmlPath, pdfPath); err != nil {
		return err
	}

	info, err := os.Stat(pdfPath)
	if err != nil {
		return err
	}
	fmt.Printf("book: wrote %s (%.1f MB)\n", pdfPath, float64(info.Size())/(1<<20))

	return nil
}

// loadChapters reads the spine and renders each file.
func loadChapters(files []string) ([]*Chapter, error) {
	chapters := make([]*Chapter, 0, len(files))

	number := 0
	for i, file := range files {
		source, err := os.ReadFile(file)
		if err != nil {
			return nil, fmt.Errorf("spine names %s but it is not there: %w", file, err)
		}

		ch := &Chapter{File: file}

		// The preface and the epilogue are not numbered. Everything between them is,
		// counted here rather than parsed out of the filename, so a gap in the numbering
		// on disk cannot produce a gap in the book.
		if file != "README.md" && file != "epilogue.md" {
			number++
			ch.Number = number
		}

		// The next file in the spine, so the footer can be checked against it. The last
		// unit has no next.
		next := ""
		if i+1 < len(files) {
			next = files[i+1]
		}

		if err = validate(file, source, ch.Number, next); err != nil {
			return nil, err
		}

		if err = ch.render(source); err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}

		chapters = append(chapters, ch)
	}

	return chapters, nil
}

// cleanTitle strips the "Chapter N: " prefix from an H1, and checks that the number in the
// file agrees with the number in the spine.
//
// Getting this wrong is the classic way a book ends up with two chapter sevens.
func cleanTitle(title string, number int) (string, error) {
	m := reChapterNum.FindStringSubmatch(title)
	if m == nil {
		if number > 0 {
			return "", fmt.Errorf("chapter %d must open with a heading of the form "+
				"\"# Chapter %d: Title\", but its H1 reads %q", number, number, title)
		}
		return title, nil
	}

	claimed, _ := strconv.Atoi(m[1])
	if claimed != number {
		return "", fmt.Errorf("the spine puts this at chapter %d but its heading says chapter %d", number, claimed)
	}

	return strings.TrimSpace(strings.TrimPrefix(title, m[0])), nil
}

// stripChapterTOC removes a chapter's own "## Table of Contents" block.
//
// That block is a reading aid for the file on GitHub. In the book it would be a second,
// worse copy of the table of contents that is already on the contents page, so it comes
// out: everything from the heading up to, but not including, the next "## ".
func stripChapterTOC(source []byte) []byte {
	const heading = "## Table of Contents"

	start := bytes.Index(source, []byte("\n"+heading))
	if start < 0 {
		if !bytes.HasPrefix(source, []byte(heading)) {
			return source
		}
		start = 0
	} else {
		start++ // keep the newline before it
	}

	rest := source[start+len(heading):]
	next := bytes.Index(rest, []byte("\n## "))
	if next < 0 {
		return source[:start]
	}

	out := make([]byte, 0, len(source))
	out = append(out, source[:start]...)
	out = append(out, rest[next+1:]...)

	return out
}
